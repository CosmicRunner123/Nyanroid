NativeExe nativeExe(const std::string& fileName, bool is64) {
    if (is64) return NativeExe::Phantom;
    std::string n = toLowerAscii(fileName);
    if (n.find("totono") != std::string::npos) return NativeExe::Totono;
    if (n.find("muramasa") != std::string::npos) return NativeExe::Muramasa;
    if (n.find("mojika") != std::string::npos) return NativeExe::Mojika;
    if (n.find("saya") != std::string::npos) return NativeExe::Saya;
    return NativeExe::Unknown;
}

uint64_t nativeAddress(const NativeName& n, NativeExe exe) {
    switch (exe) {
        case NativeExe::Muramasa: return n.muramasa;
        case NativeExe::Totono: return n.totono;
        case NativeExe::Phantom: return n.phantom;
        case NativeExe::Mojika: return n.mojika;
        case NativeExe::Saya: return n.saya;
        case NativeExe::Unknown: break;
    }
    return 0;
}

