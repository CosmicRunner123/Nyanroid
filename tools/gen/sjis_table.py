#!/usr/bin/env python3
"""Regenerates core/src/common/sjis_table.inc: Shift-JIS as Windows decodes it (code page 932,
with the NEC and IBM extensions), which is what CatSystem2 games are written in.

Layout (UTF-16 code units, big-endian pairs): [0x000, 0x100) single bytes; then a 0x1000-entry
block per lead-byte nibble section 0x8, 0x9, 0xE, 0xF, indexed by ((lead & 0xF) << 8) | trail.
Unmapped codes are 0.
"""
import pathlib

BASES = {0x8: 0x100, 0x9: 0x1100, 0xE: 0x2100, 0xF: 0x3100}
table = [0] * 0x4100


def cp932(raw: bytes) -> int:
    try:
        s = raw.decode("cp932")
    except UnicodeDecodeError:
        return 0
    return ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0


for b in range(0x100):
    if b >> 4 not in BASES or b in (0x80, 0xF0) or b >= 0xFD:
        table[b] = b if b < 0x80 else cp932(bytes([b]))
for lead in range(0x80, 0x100):
    if lead >> 4 not in BASES:
        continue
    for trail in range(0x40, 0x100):
        table[BASES[lead >> 4] + ((lead & 0xF) << 8) + trail] = cp932(bytes([lead, trail]))

out = pathlib.Path(__file__).resolve().parents[2] / "core/src/common/sjis_table.inc"
lines = ["// Shift-JIS (Windows code page 932) -> UTF-16BE lookup table. Generated by tools/gen/sjis_table.py.",
         "", f"static const unsigned char kSjisTable[{len(table) * 2}] = {{"]
flat = [x for cp in table for x in (cp >> 8, cp & 0xFF)]
for i in range(0, len(flat), 16):
    lines.append("\t" + ", ".join(f"0x{x:02x}" for x in flat[i:i + 16]) + ",")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({len(flat)} bytes)")
